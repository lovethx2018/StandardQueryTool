# 国标公告列表：标题含下列整类则跳过（不进入软件列表）
ANNOUNCEMENT_TITLE_EXCLUDE = (
    '外文版',
    '标准样品',
    '国家标准样品',
)


def is_civil_std_name(std_name):
    """标准名称是否命中土建/建材等领域关键词。"""
    name = (std_name or '').strip()
    if not name:
        return False
    return any(w in name for w in CIVIL_NAME_KEYWORDS)


def is_excluded_announcement_title(title):
    """公告标题是否属于明显无关整类（外文版、标准样品等）。"""
    t = (title or '').strip()
    if not t:
        return False
    return any(x in t for x in ANNOUNCEMENT_TITLE_EXCLUDE)


def civil_engineering_boost(std_no, std_name):
    """建筑工程/公路/市政/水利等领域加权（只加分，不否决其他领域）。"""
    import re
    boost = 0.0
    no = (std_no or '').strip()
    name = (std_name or '').strip()
    m = re.match(r'^([A-Za-z]+(?:/[A-Za-z]+)?)', no)
    if m:
        prefix = m.group(1).upper().replace(' ', '')
        boost += CIVIL_PREFIX_BOOST.get(prefix, 0.0)
    hits = sum(1 for w in CIVIL_NAME_KEYWORDS if w in name)
    if hits:
        boost += 55.0 + min(hits - 1, 3) * 8.0
    return boost
